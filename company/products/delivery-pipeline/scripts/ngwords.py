NG = {
    "断定": ["必ず", "絶対", "確実", "間違いなく", "100%", "１００％", "完璧", "誰でも簡単に"],
    "最上級・順位": ["No.1", "NO.1", "ナンバーワン", "ナンバー1", "日本一", "業界一", "業界最安", "業界初",
                 "最安", "最高", "最強", "最大級", "唯一", "どこよりも", "圧倒的"],
    "煽り・偽の限定": ["今すぐ", "今だけ", "限定", "先着", "残りわずか", "ラスト", "急いで", "お見逃しなく"],
    "効果の約束": ["完治", "治る", "劇的", "必ず効果", "効果を保証", "稼げる", "儲かる", "月収", "売上が上がる", "売上が倍"],
    "要根拠の実績表現": ["受賞", "お客様の声", "お客さまの声", "導入実績", "累計", "満足度", "リピート率",
                  "メディア掲載", "テレビで紹介", "口コミ", "保証"],
    "未記入": ["{{", "}}", "【要記入", "TODO", "lorem ipsum"],
}


def find_hits(text, allow=()):
    """[(行番号, 区分, 語, 行の内容), ...]。allow に入れた語は除外（根拠がある場合に人が指定）。"""
    out = []
    for i, line in enumerate(text.splitlines(), 1):
        low = line.lower()
        for cat, words in NG.items():
            for w in words:
                if w in allow:
                    continue
                if w in line or (w.isascii() and w.lower() in low):
                    out.append((i, cat, w, line.strip()[:60]))
    return out
